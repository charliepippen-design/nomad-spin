/**
 * Compiles translated content into the modules the app loads:
 *
 *   content/cities/<locale>/<cityId>.json        -> src/locales/<locale>/cities.generated.ts
 *   content/guides/<locale>/<english-slug>.{md,json} -> src/locales/<locale>/guides.generated.ts
 *   which pages exist in which language          -> src/locales/manifest.generated.json
 *
 * Only files with "status": "published" are emitted. A page that is not in the
 * manifest has no URL in that language: links, hreflang, sitemap and prerender
 * all read the manifest, so a draft can sit in the repo without going live.
 *
 * Runs in predev/prebuild; run by hand with: npx tsx scripts/sync-locales.ts
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { DEFAULT_LOCALE, LOCALES, LOCALE_INFO, type Locale } from '../src/i18n/config';
import { citySlug } from '../src/lib/citySlug';
import { readCityFiles, readGuideFiles } from './locale-content';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const LOCALES_DIR = path.resolve(__dirname, '../src/locales');

function plainText(md: string): string {
  return md
    .replace(/<[^>]+>/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[#*`_~>|-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function excerpt(md: string): string {
  const firstPara = md
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .find((p) => p && !p.startsWith('#') && !p.startsWith('>') && !p.startsWith('|'));
  const text = plainText(firstPara ?? md);
  return text.length <= 160 ? text : `${text.slice(0, 157).replace(/\s+\S*$/, '')}…`;
}

function toTemplateLiteral(s: string): string {
  return '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

export interface LocaleOutput {
  citiesSource: string;
  guidesSource: string;
  manifest: { cities: string[]; guides: Record<string, string> };
}

export function buildLocale(locale: Locale): LocaleOutput {
  const cityEntries = readCityFiles(locale).filter((entry) => entry.data.status === 'published');
  const cityLines = cityEntries.map(({ id, data }) => {
    const value = {
      ...(data.name ? { name: data.name } : {}),
      pros: data.pros,
      cons: data.cons,
      ...(data.legalNotes?.length ? { legalNotes: data.legalNotes } : {}),
      ...(data.taxation ? { taxation: data.taxation } : {}),
      ...(data.visaNote ? { visaNote: data.visaNote } : {}),
    };
    return `  ${JSON.stringify(id)}: ${JSON.stringify(value)},`;
  });
  const citiesSource = `// AUTO-GENERATED by scripts/sync-locales.ts: do not edit by hand.
// Edit content/cities/${locale}/<cityId>.json instead.
import type { CityTranslation } from '../../i18n/dictionary';

export const cities: Record<string, CityTranslation> = {${cityLines.length ? `\n${cityLines.join('\n')}\n` : ''}};
`;

  const guideEntries = readGuideFiles(locale).filter((entry) => entry.data.status === 'published');
  const guideBlocks = guideEntries.map(({ sourceSlug, data, markdown, source }) => {
    const words = plainText(markdown).split(' ').filter(Boolean).length;
    const readTime = LOCALE_INFO[locale].readTime.replace('{n}', String(Math.max(1, Math.round(words / 200))));
    const shortTitle = data.seo?.short_title?.trim();
    return `  {
    id: ${JSON.stringify(source.id)},
    sourceSlug: ${JSON.stringify(sourceSlug)},
    slug: ${JSON.stringify(data.slug)},
    title: ${JSON.stringify(data.title)},
    seoTitle: ${JSON.stringify(data.seo?.meta_title ?? data.title)},${shortTitle ? `\n    shortTitle: ${JSON.stringify(shortTitle)},` : ''}
    excerpt: ${JSON.stringify(data.seo?.meta_description ?? excerpt(markdown))},
    date: ${JSON.stringify(source.date)},
    updated: ${JSON.stringify(source.updated ?? source.date)},
    readTime: ${JSON.stringify(readTime)},
    relatedDestinations: ${JSON.stringify(source.relatedDestinations ?? [])},
    content: ${toTemplateLiteral(markdown)},
  }`;
  });
  const guidesSource = `// AUTO-GENERATED by scripts/sync-locales.ts: do not edit by hand.
// Edit content/guides/${locale}/<english-slug>.md and .json instead.
import type { LocalizedGuide } from '../../i18n/dictionary';

export const guides: LocalizedGuide[] = [${guideBlocks.length ? `\n${guideBlocks.join(',\n')}\n` : ''}];
`;

  return {
    citiesSource,
    guidesSource,
    manifest: {
      cities: cityEntries.map(({ city }) => citySlug(city)).sort(),
      guides: Object.fromEntries(guideEntries.map(({ sourceSlug, data }) => [sourceSlug, data.slug])),
    },
  };
}

/** Locales whose bundle imports the generated modules (see src/locales/<locale>/index.ts). */
export function contentLocales(): Locale[] {
  return LOCALES.filter(
    (locale) => locale !== DEFAULT_LOCALE && fs.existsSync(path.join(LOCALES_DIR, locale, 'cities.generated.ts')),
  );
}

export function buildManifestSource(): string {
  const manifest: Record<string, LocaleOutput['manifest']> = {};
  for (const locale of contentLocales()) manifest[locale] = buildLocale(locale).manifest;
  return JSON.stringify(manifest, null, 2) + '\n';
}

function writeIfChanged(file: string, source: string): boolean {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf-8').replace(/\r\n/g, '\n') : '';
  if (prev === source) return false;
  fs.writeFileSync(file, source);
  return true;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === __filename;
if (isMain) {
  for (const locale of contentLocales()) {
    const out = buildLocale(locale);
    const changed = [
      writeIfChanged(path.join(LOCALES_DIR, locale, 'cities.generated.ts'), out.citiesSource),
      writeIfChanged(path.join(LOCALES_DIR, locale, 'guides.generated.ts'), out.guidesSource),
    ].some(Boolean);
    console.log(
      `locale ${locale}: ${out.manifest.cities.length} city page(s), ${Object.keys(out.manifest.guides).length} guide(s)${changed ? ' (updated)' : ''}`,
    );
  }
  writeIfChanged(path.join(LOCALES_DIR, 'manifest.generated.json'), buildManifestSource());
}
